// The machine rail's pixel pets. A pet is a machine's identity: the shape says
// which machine it is, and the colour only says how the tile is being touched
// — at rest, hovered, chosen. One drawing therefore serves every state the
// rail has, and no state needs a colour of its own.
//
// Each pet is a 16×16 grid of three characters: '#' the body, drawn in
// whatever colour the tile carries; '+' the same colour at 55%, for cheeks,
// muzzles and screens; '.' a hole the background shows through. The eyes are
// holes, so every pet looks at you from inside its tile.
//
// The grids are drawn one pixel to a point: the rail shows them at
// machinePetSize, so a pixel of the drawing is a pixel on screen and nothing
// blurs. They are drawn on a 16-unit canvas with a margin all round, the way
// the app icon keeps one inside its slot.

type petIcon struct {
	key    string // the settings file stores this
	zh     string // the menu's Chinese name
	en     string // the menu's English name
	series string // the family the menu groups the pet under
	rows   []string
}

