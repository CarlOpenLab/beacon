// petGlyphs holds one parsed SVG per pet, built once: the menu and the rail
// share the same drawings, and parsing thirty-two documents at startup costs
// less than parsing one per frame. It is a var initialized from a function, so
// Go's initialization order fills it before the menu's choices read from it.
var petGlyphs = buildPetGlyphs()

func buildPetGlyphs() map[string]*ui.SVG {
	glyphs := make(map[string]*ui.SVG, len(petCatalog))
	for _, p := range petCatalog {
		glyphs[p.key] = p.svg()
	}
	return glyphs
}

// petSVG turns a grid into a document of rects. Runs of one row merge
// sideways, and runs that keep their span merge downward, so a pet is a few
// dozen rects rather than two hundred. The body draws first and the 55% tone
// over it; the two never share a pixel, so a cheek never covers an outline.
func (p petIcon) svg() *ui.SVG {
	var body, shade strings.Builder
	p.emit(&body, '#')
	p.emit(&shade, '+')
	doc := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">` +
		`<g fill="currentColor">` + body.String() + `</g>` +
		`<g fill="currentColor" fill-opacity="0.55">` + shade.String() + `</g></svg>`
	return ui.MustParseSVG([]byte(doc))
}

type petRun struct{ x, w, y0 int }

func (p petIcon) emit(b *strings.Builder, class byte) {
	place := func(r petRun, h int) {
		b.WriteString(`<rect x="` + strconv.Itoa(r.x) + `" y="` + strconv.Itoa(r.y0) +
			`" width="` + strconv.Itoa(r.w) + `" height="` + strconv.Itoa(h) + `"/>`)
	}
	var open []petRun
	for y, row := range p.rows {
		var cur []petRun
		for x := 0; x < len(row); x++ {
			if row[x] != class {
				continue
			}
			x0 := x
			for x < len(row) && row[x] == class {
				x++
			}
			cur = append(cur, petRun{x0, x - x0, y})
		}
		var still []petRun
		for _, r := range open {
			kept := false
			for _, c := range cur {
				if c.x == r.x && c.w == r.w {
					kept = true
					break
				}
			}
			if kept {
				still = append(still, r)
			} else {
				place(r, y-r.y0)
			}
		}
		for _, c := range cur {
			novel := true
			for _, s := range still {
				if s.x == c.x && s.w == c.w {
					novel = false
					break
				}
			}
			if novel {
				still = append(still, c)
			}
		}
		open = still
	}
	for _, r := range open {
		place(r, len(p.rows)-r.y0)
	}
}
