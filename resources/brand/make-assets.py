#!/usr/bin/env python3
"""Kept as the old entry point: brand art now comes from resources/brand/make-mark.py.

The mascot-era master (resources/brand/mark.png, a whale) is no longer what the
icon shows — Beacon's mark is drawn from geometry so the 16px favicon is the same
drawing as the app icon instead of a shrunken portrait. Running this script does
what make-mark.py does, so nobody silently rebuilds the old art over the new.
"""

import os
import runpy

HERE = os.path.dirname(os.path.abspath(__file__))

if __name__ == "__main__":
    print("brand art is generated by make-mark.py; running it")
    runpy.run_path(os.path.join(HERE, "make-mark.py"), run_name="__main__")
